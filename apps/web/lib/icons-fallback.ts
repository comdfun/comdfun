// Temporary pixel art used until packages/art (@company/art) exists. next.config.mjs aliases "@company/art" to this
// file when the package is absent. Same surface as the expected package: icons (16×16 SVG strings), logoSvg(),
// wordmarkSvg(), renderCounsel(tokenId). All SVGs use currentColor so CSS can tint them.

type Grid = string[];

function gridSvg(rows: Grid, opts: { size?: number; title?: string } = {}) {
  const h = rows.length;
  const w = rows[0].length;
  let rects = "";
  for (let y = 0; y < h; y++) {
    const row = rows[y];
    let x = 0;
    while (x < w) {
      const c = row[x];
      if (c === "." || c === " ") {
        x++;
        continue;
      }
      let run = 1;
      while (x + run < w && row[x + run] === c) run++;
      const op = c === "+" ? ' opacity=".45"' : c === "o" ? ' fill="#000"' : "";
      rects += `<rect x="${x}" y="${y}" width="${run}" height="1"${op}/>`;
      x += run;
    }
  }
  const size = opts.size ?? 16;
  const title = opts.title ? `<title>${opts.title}</title>` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${size}" height="${Math.round((size * h) / w)}" shape-rendering="crispEdges" fill="currentColor">${title}${rects}</svg>`;
}

