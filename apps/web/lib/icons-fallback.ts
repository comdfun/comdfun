// 3×5 pixel font for the wordmark
const F: Record<string, string> = {
  T: "### .#. .#. .#. .#.", H: "#.# #.# ### #.# #.#", E: "### #.. ##. #.. ###", C: "### #.. #.. #.. ###",
  O: "### #.# #.# #.# ###", M: "#.# ### ### #.# #.#", P: "### #.# ### #.. #..", A: "### #.# ### #.# #.#",
  N: "##. #.# #.# #.# #.#", Y: "#.# #.# ### .#. .#.", " ": "... ... ... ... ...",
};
export function wordmarkSvg(text = "COMPANY.MD") {
  const rows = ["", "", "", "", ""];
  for (const ch of text.toUpperCase()) {
    const g = (F[ch] ?? F[" "]).split(" ");
    for (let r = 0; r < 5; r++) rows[r] += g[r] + ".";
  }
  return gridSvg(rows, { size: rows[0].length * 3, title: text });
}

// ------------- tiny deterministic Counsel portrait (fallback only) -------------
function rnd(seed: number) {
  let s = seed >>> 0 || 1;
  return () => {
    s ^= s << 13;
    s ^= s >>> 17;
    s ^= s << 5;
    return (s >>> 0) / 4294967296;
  };
}
const SKIN = ["#f1c9a5", "#e0ac83", "#c68a5e", "#9a6640", "#6e4529", "#4a2e1b", "#b8c0c8", "#c9a227"];
const WIG = ["#e9e3d3", "#d8d2c2", "#3a2a1a", "#111111", "#7a5230", "#b0aa9a"];
const COAT = ["#111111", "#1c2a44", "#2b2b2b", "#2a2018", "#3b2f22", "#0d0d0d"];
const BACK = ["#000000", "#2a1a0e", "#14202a", "#1e1408", "#2a2410"];
const PRACTICE = ["Corporate", "Securities", "Litigation", "Contracts", "Tax", "IP", "Regulatory", "Arbitration", "Bankruptcy", "Admiralty"];

export function renderCounsel(tokenId: number, opts: { size?: number } = {}) {
  const r = rnd(tokenId * 2654435761 + 7);
  const pick = <T,>(a: T[]) => a[Math.floor(r() * a.length)];
  const skin = pick(SKIN);
  const wig = pick(WIG);
  const coat = pick(COAT);
  const back = pick(BACK);
  const bands = r() > 0.4;
  const specs = r() > 0.6;
  const size = opts.size ?? 256;
  const px: string[] = [];
  const P = (x: number, y: number, w: number, h: number, c: string) => px.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${c}"/>`);
  P(0, 0, 16, 16, back);
  P(4, 1, 8, 4, wig); // wig top
  P(3, 3, 2, 6, wig);
  P(11, 3, 2, 6, wig);
  P(5, 4, 6, 6, skin); // face
  P(6, 6, 1, 1, "#000");
  P(9, 6, 1, 1, "#000");
  if (specs) {
    P(5, 5, 3, 1, "#c9a227");
    P(8, 5, 3, 1, "#c9a227");
  }
  P(7, 8, 2, 1, "#5a2a20");
  P(3, 10, 10, 6, coat);
  P(2, 12, 12, 4, coat);
  P(6, 10, 4, 2, "#e9e3d3");
  if (bands) P(7, 12, 2, 3, "#e9e3d3");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="${size}" height="${size}" shape-rendering="crispEdges">${px.join("")}</svg>`;
  return {
    svg,
    name: `Counsel #${String(tokenId).padStart(4, "0")}`,
    attributes: [
      { trait_type: "Practice", value: PRACTICE[tokenId % PRACTICE.length] },
      { trait_type: "Chambers", value: `Chambers ${Math.floor(tokenId / 100) + 1}` },
    ],
  };
}
