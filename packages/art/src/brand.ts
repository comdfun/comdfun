const ON = 0xffffff;

function gridRaster(g: readonly string[], c: Color = ON): Raster {
  const r = new Raster(g[0].length, g.length);
  g.forEach((row, y) => [...row].forEach((ch, x) => ch === "#" && r.set(x, y, c)));
  return r;
}

/** Single-fill SVG from a raster: every non-transparent pixel painted with `fill`. */
function monoSvg(r: Raster, fill: string, size?: { width: number; height: number }, title?: string): string {
  const rr = r.clone();
  rr.map(() => 1);
  return rr.toSvg({ ...size, title }).replace(/<g fill="#000001">/g, `<g fill="${fill}">`);
}

