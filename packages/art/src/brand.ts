/**
 * Company.md mark (32×32 master): scales of justice in a pedimented portico.
 * Default is the full-colour arcade mark; `color` gives a single-colour version (e.g. "#FFC83D" or "currentColor").
 */
export function logoSvg(opts: { size?: number; color?: string; background?: string | null } = {}): string {
  const size = opts.size ?? 256;
  const bg = opts.background === undefined ? "#000000" : opts.background;
  let svg = opts.color
    ? monoSvg(monoMark(mark32()), opts.color, { width: size, height: size }, "Company.md")
    : mark32().toSvg({ width: size, height: size, title: "Company.md" });
  if (bg) svg = svg.replace("</title>", `</title><rect width="32" height="32" fill="${bg}"/>`);
  return svg;
}

export const WORDMARK = "COMPANY.MD";

/** Bespoke 5×7 capitals for the wordmark (the 3×5 docket font is for small labels). */
