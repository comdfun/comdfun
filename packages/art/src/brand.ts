export type IconName = keyof typeof ICON_GRIDS;

for (const [k, g] of Object.entries(ICON_GRIDS)) {
  if (g.length !== 16 || g.some((r) => r.length !== 16)) throw new Error(`icon ${k} must be 16×16`);
}

export function iconSvg(name: IconName, opts: { size?: number; title?: string } = {}): string {
  const size = opts.size ?? 16;
  return monoSvg(gridRaster(ICON_GRIDS[name]), "currentColor", { width: size, height: size }, opts.title);
}

/** 16×16 pixel icons as SVG strings, painted with currentColor. */
export const icons: Record<IconName, string> = Object.fromEntries(
  (Object.keys(ICON_GRIDS) as IconName[]).map((k) => [k, iconSvg(k)]),
) as Record<IconName, string>;
